window.SM = window.SM || {};

window.SM.expenseProductPurchases = (catalog = [], initialRows = [], createUrl = '') => ({
    catalog: Array.isArray(catalog) ? catalog : [],
    rows: Array.isArray(initialRows) ? initialRows : [],
    createUrl,
    changed: false,
    expanded: false,
    nextKey: 1,
    quickCreateName: '',
    quickCreateSku: '',
    quickCreateSkuTouched: false,
    quickCreateSkuAutoGenerated: false,
    quickCreateUnit: 'each',
    quickCreateError: '',
    quickCreateSaving: false,
    init() {
        this.rows = this.rows.map((row) => this.normaliseRow(row));
    },
    formatAmount(value) {
        const raw = String(value ?? '').trim();
        if (raw === '') return '';
        const amount = Number(raw);

        return Number.isFinite(amount) && amount >= 0 ? amount.toFixed(2) : raw;
    },
    formatTotal(row, input) {
        row.total_cost_ex_tax = this.formatAmount(input.value);
        input.value = row.total_cost_ex_tax;
    },
    normaliseRow(row = {}) {
        const key = this.nextKey++;
        const productId = String(row.product_id ?? '');
        const product = this.catalog.find((option) => String(option.id) === productId);
        const individualUnits = row.individual_units === undefined
            ? ['physical', 'kit'].includes(product?.product_type) && !row.id && !row.product_variant_id
            : [true, 1, '1'].includes(row.individual_units);
        const purchasePack = [true, 1, '1'].includes(row.purchase_pack);

        const normalised = {
            key,
            id: String(row.id ?? ''),
            product_id: productId,
            item_name: String(row.item_name || product?.name || ''),
            product_variant_id: String(row.product_variant_id ?? ''),
            individual_units: individualUnits && !purchasePack,
            purchase_pack: purchasePack,
            saved_purchase_pack_units: purchasePack ? Number(row.units_per_purchase) || null : null,
            purchase_choice: purchasePack ? 'supplier' : individualUnits ? 'individual' : String(row.product_variant_id ?? ''),
            add_inventory: false,
            quantity: String(row.quantity ?? ''),
            total_cost_ex_tax: this.formatAmount(row.total_cost_ex_tax),
            evidence: {
                text: String(row.evidence?.text || ''),
                page: Number(row.evidence?.page) || 0,
            },
            touched: false,
            aiSuggested: false,
        };
        normalised.add_inventory = row.add_inventory === undefined
            ? this.tracksInventory(normalised)
            : [true, 1, '1'].includes(row.add_inventory);

        return normalised;
    },
    productFor(row) { return this.catalog.find((item) => String(item.id) === String(row.product_id)) || null; },
    tracksInventory(row) {
        const item = this.productFor(row);
        if ((row.individual_units || row.purchase_pack) && !item?.shared_inventory && item?.pack_units > 1) return false;
        const variant = item?.variants?.find((option) => String(option.id) === String(row.product_variant_id));
        return Boolean(variant ? variant.tracks_inventory : item?.tracks_inventory);
    },
    itemChanged(row) {
        row.product_variant_id = '';
        const product = this.productFor(row);
        row.saved_purchase_pack_units = null;
        row.purchase_pack = Boolean(product?.has_material_measurements && product?.purchase_pack_units > 1);
        row.individual_units = !row.purchase_pack && ['physical', 'kit'].includes(product?.product_type);
        row.purchase_choice = row.purchase_pack ? 'supplier' : row.individual_units ? 'individual' : '';
        row.add_inventory = this.tracksInventory(row);
        this.markChanged(row);
    },
    purchaseChoiceChanged(row) {
        row.individual_units = row.purchase_choice === 'individual';
        row.purchase_pack = row.purchase_choice === 'supplier';
        row.product_variant_id = row.individual_units || row.purchase_pack ? '' : row.purchase_choice;
        row.add_inventory = this.tracksInventory(row);
        this.markChanged(row);
    },
    purchasePackUnits(row) {
        return row.saved_purchase_pack_units || this.productFor(row)?.purchase_pack_units || 1;
    },
    supplierPackLabel(row) {
        const units = this.purchasePackUnits(row);
        const unit = this.productFor(row)?.unit || 'piece';
        const label = ['each', 'unit', 'units'].includes(unit.toLowerCase()) ? 'piece' : unit;

        return `Supplier pack (${units} ${window.SM.pluralize(label, units)})`;
    },
    unitFor(row) {
        const product = this.productFor(row);
        if (row.purchase_pack) return 'pack';
        if (['physical', 'kit'].includes(product?.product_type) && !row.individual_units) {
            const variant = product.variants?.find(option => String(option.id) === String(row.product_variant_id));
            if (Number(variant?.pack_units ?? product.pack_units) > 1) return 'pack';
        }

        return product?.unit || '';
    },
    markChanged(row = null) {
        this.changed = true;
        if (row) row.touched = true;
    },
    addRow() {
        this.rows.push(this.normaliseRow({ quantity: '1' }));
        this.markChanged();
    },
    openCreateItemDialog() {
        this.quickCreateName = '';
        this.quickCreateSku = '';
        this.quickCreateSkuTouched = false;
        this.quickCreateSkuAutoGenerated = false;
        this.quickCreateUnit = 'each';
        this.quickCreateError = '';
        document.getElementById('expense-product-item-create-dialog')?.showModal();
        this.$nextTick(() => document.getElementById('expense-product-item-create-name')?.focus());
    },
    slugify(value) {
        return String(value || '')
            .toLowerCase()
            .normalize('NFD')
            .replace(/[\u0300-\u036f]/g, '')
            .replace(/[^a-z0-9]+/g, '-')
            .replace(/^-+|-+$/g, '')
            .replace(/-{2,}/g, '-')
            .slice(0, 120);
    },
    generateQuickCreateSkuFromName() {
        if (this.quickCreateSkuTouched || String(this.quickCreateSku || '').trim() !== '') {
            return;
        }

        this.quickCreateSku = this.slugify(this.quickCreateName);
        this.quickCreateSkuAutoGenerated = true;
    },
    handleQuickCreateSkuInput() {
        this.quickCreateSkuTouched = String(this.quickCreateSku || '').trim() !== '';
        this.quickCreateSkuAutoGenerated = false;
    },
    async createProduct() {
        if (this.quickCreateSaving) return;

        this.quickCreateError = '';
        this.quickCreateSaving = true;
        try {
            const csrfToken = document.querySelector('meta[name="csrf-token"]')?.content || '';
            const response = await fetch(this.createUrl, {
                method: 'POST',
                credentials: 'same-origin',
                headers: {
                    Accept: 'application/json',
                    'Content-Type': 'application/json',
                    'X-Requested-With': 'XMLHttpRequest',
                    ...(csrfToken ? { 'X-CSRF-TOKEN': csrfToken } : {}),
                },
                body: JSON.stringify({
                    title: this.quickCreateName.trim(),
                    sku: this.quickCreateSku.trim(),
                    sku_auto_generated: this.quickCreateSkuAutoGenerated,
                    purchase_unit: this.quickCreateUnit.trim() || 'each',
                }),
            });
            const payload = await response.json().catch(() => ({}));

            if (!response.ok) {
                const validationMessage = payload.errors && typeof payload.errors === 'object'
                    ? Object.values(payload.errors).flat().find((message) => typeof message === 'string' && message.trim())
                    : null;
                throw new Error(response.status === 419
                    ? 'Your session has expired. Reload the page and try again.'
                    : validationMessage || payload.message || 'Could not create the material. Please try again.');
            }

            const item = payload.item;
            if (!item || !Number(item.id) || !item.name) {
                throw new Error('The material was created, but could not be added to this expense. Reload the page and try again.');
            }

            const nextCatalog = [...this.catalog.filter((option) => Number(option.id) !== Number(item.id)), item]
                .sort((left, right) => String(left.name).localeCompare(String(right.name)));
            this.catalog.splice(0, this.catalog.length, ...nextCatalog);
            const row = this.normaliseRow({
                product_id: String(item.id),
                item_name: item.name,
                quantity: '1',
            });
            this.rows.push(row);
            this.markChanged(row);
            this.expanded = true;
            document.getElementById('expense-product-item-create-dialog')?.close();
        } catch (error) {
            this.quickCreateError = error instanceof Error ? error.message : 'Could not create the material. Please try again.';
        } finally {
            this.quickCreateSaving = false;
        }
    },
    removeRow(key) {
        this.rows = this.rows.filter((row) => row.key !== key);
        this.markChanged();
    },
    applyAiItems(items) {
        if (!Array.isArray(items)) return 0;

        const matchedRows = new Set();
        let prepared = 0;
        for (const item of items) {
            const productId = String(Number(item?.product_id) || '');
            const quantity = String(item?.quantity ?? '').trim();
            const totalCost = String(item?.total_cost_ex_tax ?? '').trim();
            const evidence = {
                text: String(item?.evidence?.text || '').slice(0, 300),
                page: Number(item?.evidence?.page) || 0,
            };
            const product = this.catalog.find((option) => String(option.id) === productId && option.status !== 'archived');
            const purchasePack = item?.purchase_pack === true;
            if (!product || !/^\d+(?:\.\d+)?$/.test(quantity) || Number(quantity) <= 0 || !/^\d+(?:\.\d+)?$/.test(totalCost)) {
                continue;
            }
            if (purchasePack && (!product.has_material_measurements || product.product_type !== 'physical' || product.purchase_pack_units <= 1)) continue;

            const existingRow = this.rows.find((row) => {
                return !row.touched
                    && !matchedRows.has(row.key)
                    && String(row.product_id) === productId
                    && !row.product_variant_id
                    && row.purchase_pack === purchasePack
                    && (!purchasePack || this.purchasePackUnits(row) === product.purchase_pack_units)
                    && row.individual_units === (!purchasePack && ['physical', 'kit'].includes(product.product_type));
            });
            if (existingRow) {
                existingRow.quantity = quantity;
                existingRow.total_cost_ex_tax = this.formatAmount(totalCost);
                existingRow.evidence = evidence;
                existingRow.aiSuggested = true;
                matchedRows.add(existingRow.key);
            } else {
                const row = this.normaliseRow({
                    product_id: productId,
                    purchase_pack: purchasePack,
                    item_name: product.name,
                    quantity,
                    total_cost_ex_tax: totalCost,
                    evidence,
                });
                row.aiSuggested = true;
                this.rows.push(row);
                matchedRows.add(row.key);
            }
            prepared++;
        }

        if (prepared > 0) this.markChanged();

        return prepared;
    },
});
